const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const html = fs.readFileSync('index.html', 'utf8');
const match = html.match(/function machineInputHasCapacity\(dest,packet,pending=\[\]\)\{[\s\S]*?\nfunction canAcceptArrival/);
assert(match, 'machine input capacity guard exists');
const fnSource = match[0].replace(/\nfunction canAcceptArrival$/, '');
const sandbox = { state: { machineStock: { m1: { 'Iron Ore': 3, 'Copper Ore': 1 } } } };
vm.createContext(sandbox);
vm.runInContext(fnSource + '\nthis.check=machineInputHasCapacity;', sandbox);
const machine = { id: 'm1', type: 'machine', bufferCapacity: 4 };
assert.strictEqual(sandbox.check(machine, { item: 'Iron Ore' }, []), true, 'accept while below limit');
assert.strictEqual(sandbox.check(machine, { item: 'Iron Ore' }, [{item:'Iron Ore'}]), false, 'do not accept packet that would fill limit via same-tick arrival');
assert.strictEqual(sandbox.check(machine, { item: 'Iron Ore' }, [{item:'Iron Ore'}, {item:'Iron Ore'}]), false, 'reject while at/over limit');
assert.strictEqual(sandbox.check(machine, { item: 'Copper Ore' }, []), true, 'each resource has its own input limit');
sandbox.state.machineStock.m1['Iron Ore'] = 2;
assert.strictEqual(sandbox.check(machine, { item: 'Iron Ore' }, []), true, 'resume intake once stock drops below limit');
assert(html.includes('Incoming packets wait at the end of their belt/pipe'));
console.log('Input limit/backpressure tests passed (5 checks).');
