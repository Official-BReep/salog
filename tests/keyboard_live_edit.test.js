const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync(new URL('../index.html', `file://${__filename}`), 'utf8');
assert.match(html, /if\(e\.key==='F6'\)\{e\.preventDefault\(\);step\(\);return;\}/, 'F6 should step without pausing first');
assert.doesNotMatch(html, /if\(e\.key==='F6'\)\{e\.preventDefault\(\);stop\(\);step\(\);return;\}/, 'F6 must not stop simulation');
const loadHandler = html.match(/\$\('#fileInput'\)\.addEventListener\('change',[\s\S]*?\n\$\('#inventoryExportBtn'\)/)?.[0] || '';
assert.ok(loadHandler.includes('Layout imported while simulation continues running.'), 'layout import reports live status');
assert.ok(!/Invalid layout'\);stop\(\);state\.nodes=/.test(loadHandler), 'layout import should not stop simulation');
assert.ok(/function loadSnapshot\(d\)\{if\(!d\|\|!Array\.isArray\(d\.nodes\)\|\|!Array\.isArray\(d\.edges\)\)return;state\.nodes=/.test(html), 'workspace snapshot should not stop simulation');
assert.match(html, /ctrl&&e\.shiftKey&&key==='l'/, 'left sidebar hotkey present');
assert.match(html, /ctrl&&e\.shiftKey&&key==='i'/, 'right sidebar hotkey present');
assert.match(html, /right-collapsed/, 'right sidebar collapse CSS present');
console.log('v9.7 live-edit and keyboard regression checks passed');
